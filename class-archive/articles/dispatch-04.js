    <p><strong>韩佳音</strong>：个人很喜欢诺兰的电影。相较于他的《蝙蝠侠：黑暗骑士》《盗梦空间》《星际穿越》，《敦刻尔克》不算特别亮眼，甚至可以说是这几部电影中口碑最差的一部。它的故事情节并不新颖——敦刻尔克的故事人人皆知；它的人物形象也并不鲜明讨喜——比起蝙蝠侠、盗梦者，撤退中的普通士兵显得平庸无奇。在某种意义上来说，与诺兰的前几部电影不同，《敦刻尔克》更像是一部电影化的 Historical Document：诺兰展示的视角是客观的，甚至可以说是冰冷的，他叙述了这个故事，用最冷色调、最灰暗的镜头将士兵们、平民们的生死放在你眼前。他并没有求着观众去共情、去流泪，他就是这样给你看，剩下的全留给你自己去感受。</p>

    <p><strong>孙刚</strong>：尽管线上集体观影由于硬件原因观感不是很佳，我仍然被《敦刻尔克》的情节深深吸引，并感到其中的深层次摄影精神。我能感到为了使该片得到绝佳效果，诺兰在拍摄前一定研究了大量历史资料。我们可以发现士兵大多是由年轻演员来表演，这与当时在敦刻尔克等待撤退的英国士兵非常年轻、且缺乏经验的史实很贴近。该片分成沙滩上的步兵部分、海军部分以及空军部分讲述，力求从不同的个人观点来呈现和构建这起历史事件。主角的台词很少，大量时间的沉默营造了战争被困下，各自求生的自私心与相信国家的荣誉感、爱国感交杂其中，氛围立刻就有了。</p>

    <p><strong>林泓</strong>：诺兰的《敦刻尔克》把作战室里的指挥策划场景全部删去，开场不交待历史背景，结尾也不交代伤亡人数。这里没有丘吉尔，没有希特勒，《敦刻尔克》宏伟的结果更是没有悬念。诺兰只是牵挂着小人物的恐惧，聚焦战争中每个个体的情绪与命运，这是最特别也是最难能可贵的。而贯彻于整部电影的，是那种惶惶不可终日的死亡威胁：面对绝境，每个人都不得不为自己的命运背水一战，才有可能活着回家。</p>

    <p><strong>刘婉清</strong>：《敦刻尔克》是一部不一样的战争片。故事分为三个时间线：敦刻尔克港口等待撤退的士兵；响应号召开着自家游艇前来救援的英国老大爷；阻挡德军空袭的英国空军。三条线各自发展，视角来回切换，最终交织在一起。比起以往枪林弹雨的战争片，这部影片更注重的是描绘人的心理和人性，也更让人共情。</p>

    <p><strong>陈欣欣</strong>：敦刻尔克这段扣人心弦的历史被诺兰以独特的方式再现了。没有复杂的故事，没有深刻的角色塑造，没有撕心裂肺的情感表达，有的只是真实的生存恐惧，赤裸裸的生存危机。这不是关于个人的英雄主义故事，这是人类关于战争的故事。战争，永远是人类的生存危机。</p>

    <p><strong>陈杨燕</strong>：《敦刻尔克》不像传统的反战片，没有高调直接地表现战争的残忍血腥，而是隐晦间接地表现敌人的存在。无一处明提纳粹，却时时表现其于联军的威胁。敌人在不时响起的子弹尖锐的呼啸声里，在急速飞驰的德国轰炸机里，在黑夜海水下潜艇突然发射的鱼雷里，还在被困于敦刻尔克海滩上 40 万联军的眼神里，以及他们紧张压抑的情绪里，甚至，朝不保夕的命运里。可能这就是艺术创作的「共鸣」部分吧：既已意会，无需言传。</p>

    <p><strong>郝艳</strong>：《敦刻尔克》是一部非常优秀的电影，看完以后我感悟很深。整部电影最吸引我的地方就是它的叙事结构：影片采用多线叙事，给观众展现了陆、海、空三方的作战情况；同时，诺兰将这三条线交叉剪辑，使得影片的整体剧情具有悬念。故事的大结局是已知的，但是单个人物的生死则是未知的。诺兰设置的悬念，就是在这样小规模的无常中，每个人物的最后命运。</p>

    <p><strong>周子杰</strong>：《敦刻尔克》并不是一部传统意义上的战争题材电影，它甚至都算不上是部「反战片」：没有领导人出镜，没有血肉横飞的场面，连德军都没真正露过一张脸，而且影片的故事也简略、零碎到了非常「薄弱」的程度，这大概是不少人难以接受的地方吧。不过，该片原本就没有那些追求，它更多是想还原那段历史的一个剪影，展现人真实可信的一面。</p>

    <p><strong>孙嘉意</strong>：《敦刻尔克》的故事核心和《1917》有些相像：单线剧情，简单不烧脑，却给人以反战深思。尸横遍野，老鼠满目，塞满尸体的河流，照得黑夜宛如白天的火光，一面是绿野花香，一面是残酷战场。反战思考随处可见，比如《乔乔兔》是一种四两拨千斤的反战表达，这部片子则表现得更加赤裸。</p>

    <p><strong>王艺琏</strong>：《敦刻尔克》是一部独特的战争片。并没有残酷血腥的厮杀，亦没有煽动人心的对话，有的只是无边的海与天，有的只是丑陋又或是高尚的灵魂。配乐恰到好处地渲染了紧张的氛围，看完以后感到非常震撼，这部电影让我从另一个角度看到了不一样的战场。</p>

    <p><strong>徐佳怡</strong>：电影讲述的是历史上著名的敦刻尔克大撤退，没有特别宏大的布局，从一个英国小兵开始一个故事的线索，为了生存，做着一切可行不可行的努力。影片的镜头多数以小人物为主，展现在灾难面前每个人的努力。祖国这两个字承载了多少人的执念：生为祖国的兵，他们无限荣耀，祖国需要时义无反顾。我敬佩这些伟大的人——我们安逸的生活，是因为总有人在用自己的生命捍卫。</p>

    <p><strong>达佈娜</strong>：敦刻尔克中我印象最深的是那位无比冷静、时刻散发着人格魅力的开船大叔。其实这位无比镇定的开船大叔是一个历史上真实存在的人——查尔斯·莱托勒（Charles Lightoller）。1940 年敦刻尔克大撤退时他已经 66 岁，但还是义无反顾地带着儿子驾船去海峡对面的战场拯救绝望的士兵。谁都没有想到，一艘小小的游艇最后救起了 130 人。这位大叔在 1952 年去世，他的传奇小船「日落号」一直都在，还参加了 2012 年的一次敦刻尔克大撤退纪念活动。</p>
    <p>敦刻尔克不是一部激情四射的战争片，表现的却是战争中普通人最真实的恐惧和无力，这也让此时出现的零星的人性光芒显得愈发的伟大。</p>

    <p><strong>孔贻如</strong>：早就对这部电影有所耳闻，一直没有找到机会观看，恰逢班会这个契机，与同学们一起观看了这部影片。这次和同学们一起观看影片的体验很不同，也很难忘。《敦刻尔克》讲述的就是二战期间著名的敦刻尔克大撤退事件。面对敌人的步步紧逼，英国政府发动人民起来营救军队。电影只有 107 分钟，但是节奏紧凑，故事细致，很好地展现了历史。电影从海陆空三个视角叙述，很好地体现了重大历史事件的厚重感。</p>

    <p><strong>王蕴怡</strong>：诺兰经常被诟病「缺少感情」「主角就是工具人」，实际上他作品的温度总是体现在一些细节处。在《敦刻尔克》里，我们从士兵的眼睛里看见了对生命的渴望；在船长的话语中感受到赤忱的爱国之心；从飞机马达的呼啸声里听见了保家卫国的咆哮。整部电影我印象最深的是影片最后，汤姆·哈迪扮演的飞行员降落在一片一望无际的沙滩上，飞机燃起的火与无垠的蓝灰色海水相连成为一条线，他的背影一直竖在那里。我们虽然看不清他的脸，却能读懂他想表达的、也是诺兰想表达的，那就是 “we will never surrender”。</p>

    <p><strong>夏莲</strong>：《敦刻尔克》的故事改编自著名的二战军事事件「敦刻尔克大撤退」。二战初期，40 万英法盟军被敌军围困于敦刻尔克的海滩之上，面对敌军步步逼近的绝境，他们不得已为自己的命运背水一战。全片向观众展示了战争的残酷和恐怖。</p>

    <p><strong>吴晓晴</strong>：「我会尊重人类寻求生存的本能，而不是真正的英雄主义。」贯彻于整部电影的，是那种惶惶不可终日的死亡威胁：面对绝境，每个人都不得不为自己的命运背水一战，才有可能活着回家。这些战争中的个体，浓缩着 40 万人的恐惧，像极了敦刻尔克灰蓝色的海水，无边无际。</p>

    <p><strong>葛婧</strong>：好的战争电影应当是这样的：不是宣扬英雄主义，而是让人真正反对战争。「撤退的意义不在于输赢，而在于求生。」《敦刻尔克》给「胜利」带来新的注解——战争结果不是关注敌军死伤人数，而是关注我军存活人数。电影的整体氛围，是在恐惧、绝望、茫然中透出勇气、希望与坚韧，同时不失历史大事件的厚重感。</p>

    <p><strong>安思齐</strong>：《敦刻尔克》展现了二战的「敦刻尔克大撤退」事件。克里斯托弗·诺兰将情节简化，省去了前因后果的故事铺垫，一开场就单刀直入，将观众带入战场，并通过大胆创新，以海、陆、空三个不同时空交织的故事结构，来展现情节的紧迫感，并推动剧情发展。视觉效果磅礴大气，刻画的士兵群像十分精彩，同时结尾也足够震撼，余味悠长。除了震撼，《敦刻尔克》还有触动心灵的动人情节：对求生的渴望、无私救人的勇气、为同胞的奉献，各种最闪亮的人性光辉都在诺兰的执导下获得了深入浅出的阐释，令《敦刻尔克》呈现出一种温暖的人文关怀及独具一格的动人气质。</p>

