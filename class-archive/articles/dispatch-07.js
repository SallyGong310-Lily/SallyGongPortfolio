    <h2>壹 · 班主任讲话</h2>
    <p>
      活动伊始，班长王蕴怡邀请班主任陈沁老师发表讲话。陈老师根据多年来学习语言的经验，与同学们分享了自己的感悟见解。首先，陈老师将自己多年来的法语语言学习历程总结为「从文字到文化」的过程：任何的语言学习者都难以逃避漫长而机械的知识输入，但是当语言学习达到一个质变的临界点，学习者的语言输出就会达到一个更高的层次，并且认识到语言背后的深层次文化，其思想水位和国际视野都不可同日而语。
